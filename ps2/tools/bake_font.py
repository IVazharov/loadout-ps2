"""Bakes Loadout Bay's text styles into a glyph atlas in C.

Renders each style from the Barlow fonts in ../assets/fonts at its exact size,
packs the glyphs into one atlas with 4-bit alpha, and writes ../src/font_data.c
for font.h. The PS2 build then needs no font renderer. Run it again after a
change to the styles or the fonts:

    python ps2/tools/bake_font.py

Needs Pillow (pip install pillow).
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"
OUT = ROOT / "src" / "font_data.c"

ATLAS_WIDTH = 512
FIRST = 0x20
# Beyond ASCII, font.h gives these characters the codes after '~'.
EXTRA = ["·", "–", "…", "›"]
CHARS = [chr(code) for code in range(FIRST, 0x7F)] + EXTRA
DIGITS = "0123456789"

# Name in font.h, font file, size in pixels, tracking, characters (None for all).
STYLES = [
    ("FONT_HERO", "Barlow-Bold.ttf", 48, 0, DIGITS + ".-% "),
    ("FONT_WORDMARK", "BarlowCondensed-Bold.ttf", 30, 2, "ABCDEFGHIJKLMNOPQRSTUVWXYZ "),
    ("FONT_HEADLINE", "Barlow-Bold.ttf", 28, 0, None),
    ("FONT_BODY", "Barlow-SemiBold.ttf", 24, 0, None),
    ("FONT_LABEL", "BarlowCondensed-SemiBold.ttf", 22, 1, None),
    ("FONT_PILL", "BarlowCondensed-Bold.ttf", 16, 0, "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 "),
]


def render_style(file, size, chars):
    font = ImageFont.truetype(str(FONTS / file), size)
    glyphs = {}
    for ch in CHARS:
        if chars is not None and ch not in chars:
            continue
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        image = None
        if right > left and bottom > top:
            image = Image.new("L", (right - left, bottom - top), 0)
            ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        glyphs[ch] = {"image": image, "left": left, "top": top, "advance": round(font.getlength(ch))}

    # Tabular digits: every digit takes the widest digit's advance, centred in it,
    # so addresses and counters do not shift while they change.
    widest = max((glyphs[d]["advance"] for d in DIGITS if d in glyphs), default=0)
    for d in DIGITS:
        if d in glyphs:
            glyph = glyphs[d]
            glyph["left"] += (widest - glyph["advance"]) // 2
            glyph["advance"] = widest
    return glyphs


def pack(styles):
    """Shelf-packs every glyph image with a 1-pixel gap; returns the atlas height."""
    items = [g for glyphs in styles for g in glyphs.values() if g["image"] is not None]
    items.sort(key=lambda g: -g["image"].height)
    x = y = shelf = 0
    for glyph in items:
        w, h = glyph["image"].size
        if x + w > ATLAS_WIDTH:
            x, y, shelf = 0, y + shelf + 1, 0
        glyph["x"], glyph["y"] = x, y
        x += w + 1
        shelf = max(shelf, h)
    used = y + shelf
    height = 1
    while height < used:
        height *= 2
    return height


def main():
    styles = [render_style(file, size, chars) for _, file, size, _, chars in STYLES]
    height = pack(styles)
    atlas = Image.new("L", (ATLAS_WIDTH, height), 0)
    for glyphs in styles:
        for glyph in glyphs.values():
            if glyph["image"] is not None:
                atlas.paste(glyph["image"], (glyph["x"], glyph["y"]))

    pixels = [(value * 15 + 127) // 255 for value in atlas.tobytes()]
    packed = bytes(pixels[i] | (pixels[i + 1] << 4) for i in range(0, len(pixels), 2))

    lines = [
        "// Generated by ps2/tools/bake_font.py from the Barlow fonts in ps2/assets/fonts",
        "// (SIL Open Font License 1.1, see ps2/third_party/barlow). Do not edit.",
        "",
        '#include "font.h"',
        "",
        f"const int font_atlas_width = {ATLAS_WIDTH};",
        f"const int font_atlas_height = {height};",
        "",
        "// Two pixels a byte, the first in the low four bits.",
        "const unsigned char font_atlas[] = {",
    ]
    for i in range(0, len(packed), 24):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in packed[i:i + 24]) + ",")
    lines += ["};", "", "const struct font_style font_styles[FONT_STYLE_COUNT] = {"]
    for (name, file, size, tracking, _), glyphs in zip(STYLES, styles):
        lines.append(f"    [{name}] = {{{size}, {tracking}, {{")
        for ch in CHARS:
            g = glyphs.get(ch)
            if g is None:
                lines.append("        {0, 0, 0, 0, 0, 0, 0},")
                continue
            w, h = g["image"].size if g["image"] is not None else (0, 0)
            lines.append(f"        {{{g.get('x', 0)}, {g.get('y', 0)}, {w}, {h}, {g['left']}, {g['top']}, {g['advance']}}},")
        lines.append("    }},")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"{OUT.name}: atlas {ATLAS_WIDTH}x{height}, {len(packed)} bytes")


if __name__ == "__main__":
    main()
